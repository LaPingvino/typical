# Generate src/fcotlang.h, the OpenType language-system tag to BCP 47
# table used when recording the `locl` languages of a font.
#
# Usage: gen-otlang.py path/to/harfbuzz/src/hb-ot-tag-table.hh > src/fcotlang.h
#
# The mapping is HarfBuzz's hb_ot_tag_to_language(), which is itself
# generated from the OpenType language system tag registry and the IANA
# language subtag registry: the explicit choice for ambiguous tags, else
# the first two-letter language for the tag, else the first three-letter
# one.  Entries HarfBuzz leaves commented out because its fallback covers
# them (tag == uppercased ISO 639-3 code) are included.  The Chinese tags
# are replaced by the names fontconfig's own orthographies use (zh-cn,
# zh-tw, zh-hk, zh-mo), and every tag is lowercased like the rest of
# fontconfig's languages.

import re
import sys

FC_OVERRIDES = {
    'ZHS ': 'zh-cn',
    'ZHT ': 'zh-tw',
    'ZHH ': 'zh-hk',
    'ZHTM': 'zh-mo',
}

TAG = r"HB_TAG\('(.)','(.)','(.)','(.)'\)"


def main(path):
    src = open(path, encoding='utf-8').read()
    # HarfBuzz comments out the entries where the OpenType tag is just the
    # uppercased ISO 639-3 code (/*{HB_TAG('m','o','h',' '), ...},*/), since
    # it derives those by fallback.  They are real registry entries, so the
    # regex below reads them too: they are kept on purpose.

    m = re.search(r'/\* == Start of generated table == \*/\s*/\*(.*?)\*/', src, re.S)
    header = m.group(1).strip() if m else ''

    table = {}
    amb = src[src.index('hb_ot_ambiguous_tag_to_language (hb_tag_t tag)'):]
    for m in re.finditer(r'case ' + TAG + r':.*?\n\s*return hb_language_from_string \("([^"]+)"', amb):
        table.setdefault(''.join(m.group(1, 2, 3, 4)), m.group(5))

    for name in ('ot_languages2', 'ot_languages3'):
        body = src[src.index(name + '[] = {'):]
        body = body[:body.index('\n};')]
        for m in re.finditer(r'\{' + TAG + r',\s*' + TAG + r'\}', body):
            lang = ''.join(m.group(1, 2, 3, 4)).rstrip()
            ot = ''.join(m.group(5, 6, 7, 8))
            table.setdefault(ot, lang)

    table.update(FC_OVERRIDES)

    out = sys.stdout
    out.write('/*\n * fontconfig/src/fcotlang.h\n *\n')
    out.write(' * Generated by build-aux/gen-otlang.py from HarfBuzz\'s hb-ot-tag-table.hh,\n')
    out.write(' * which in turn was generated from:\n *\n')
    for line in header.splitlines():
        line = line.strip().lstrip('*').rstrip()
        out.write(' *' + (line if line.startswith(' ') or not line else ' ' + line) + '\n')
    out.write(' *\n * Do not edit by hand.\n */\n\n')
    out.write('#define FC_OT_TAG(a, b, c, d) \\\n'
              '    ((FcChar32)(a) << 24 | (FcChar32)(b) << 16 | (FcChar32)(c) << 8 | (FcChar32)(d))\n\n')
    out.write('/* OpenType language system tag -> BCP 47 language, sorted by tag. */\n')
    out.write('typedef struct {\n    FcChar32 tag;\n    char     lang[12];\n} FcOtLang;\n\nstatic const FcOtLang fcOtLangs[] = {\n')
    width = max(len(v) for v in table.values()) + 2
    for ot in sorted(table):
        lang = table[ot].lower()
        assert len(lang) < 12, lang
        out.write("    { FC_OT_TAG ('%s', '%s', '%s', '%s'), %-*s },\n" % (*ot, width, '"%s"' % lang))
    out.write('};\n')


if __name__ == '__main__':
    main(sys.argv[1])
